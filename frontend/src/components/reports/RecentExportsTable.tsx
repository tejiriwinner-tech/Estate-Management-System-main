"use client";

import React from "react";
import { FileText, FileSpreadsheet, Download } from "lucide-react";
import { RecentExportItem } from "@/types/reportCenter";

interface RecentExportsTableProps {
  exportsList: RecentExportItem[];
  onDownload: (item: RecentExportItem) => void;
}

export function RecentExportsTable({
  exportsList,
  onDownload,
}: RecentExportsTableProps) {
  return (
    <div className="space-y-4">
      {/* Section Header */}
      <div className="flex items-center justify-between">
        <h2 className="text-base font-extrabold tracking-tight text-dark">
          Recent Exports
        </h2>
        <button
          type="button"
          onClick={() => onDownload(exportsList[0])}
          className="text-xs font-bold text-primary hover:underline cursor-pointer"
        >
          View All Exports
        </button>
      </div>

      {/* Desktop Table (>= sm) */}
      <div className="hidden sm:block overflow-hidden rounded-2xl border border-slate-100 bg-white shadow-sm">
        <table className="w-full text-left">
          <thead>
            <tr className="border-b border-slate-100 bg-slate-50/80 text-[10px] font-bold uppercase tracking-wider text-slate-400">
              <th className="py-3.5 px-6">REPORT NAME</th>
              <th className="py-3.5 px-4">GENERATED BY</th>
              <th className="py-3.5 px-4">DATE &amp; TIME</th>
              <th className="py-3.5 px-4">FORMAT</th>
              <th className="py-3.5 px-6 text-right">ACTION</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-100 text-xs">
            {exportsList.map((item) => {
              const isPdf = item.format === "PDF";
              return (
                <tr
                  key={item.id}
                  className="hover:bg-slate-50/60 transition-colors"
                >
                  {/* Report Name */}
                  <td className="py-4 px-6">
                    <div className="flex items-center gap-3">
                      {isPdf ? (
                        <FileText className="h-4 w-4 text-primary flex-shrink-0" />
                      ) : (
                        <FileSpreadsheet className="h-4 w-4 text-emerald-600 flex-shrink-0" />
                      )}
                      <span className="font-bold text-dark">
                        {item.fileName}
                      </span>
                    </div>
                  </td>

                  {/* Generated By */}
                  <td className="py-4 px-4 font-medium text-slate-600">
                    {item.generatedBy}
                  </td>

                  {/* Date & Time */}
                  <td className="py-4 px-4 font-medium text-slate-500">
                    {item.dateTime}
                  </td>

                  {/* Format Pill */}
                  <td className="py-4 px-4">
                    <span
                      className={`inline-flex items-center rounded-md px-2.5 py-0.5 text-[10px] font-extrabold uppercase tracking-wider ${
                        isPdf
                          ? "bg-rose-50 text-primary"
                          : "bg-emerald-50 text-emerald-700"
                      }`}
                    >
                      {item.format}
                    </span>
                  </td>

                  {/* Action */}
                  <td className="py-4 px-6 text-right">
                    <button
                      type="button"
                      onClick={() => onDownload(item)}
                      title={`Download ${item.fileName}`}
                      className="inline-flex h-8 w-8 items-center justify-center rounded-lg bg-slate-100 text-primary hover:bg-primary hover:text-white transition-colors cursor-pointer"
                    >
                      <Download className="h-4 w-4" />
                    </button>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      {/* Mobile Card List (< sm) */}
      <div className="block sm:hidden space-y-3">
        {exportsList.map((item) => {
          const isPdf = item.format === "PDF";
          return (
            <div
              key={item.id}
              className="flex items-center justify-between gap-3 rounded-2xl border border-slate-100 bg-white p-4 shadow-sm"
            >
              <div className="flex items-start gap-3 min-w-0">
                <div
                  className={`flex h-10 w-10 flex-shrink-0 items-center justify-center rounded-xl ${
                    isPdf
                      ? "bg-rose-50 text-primary"
                      : "bg-emerald-50 text-emerald-700"
                  }`}
                >
                  {isPdf ? (
                    <FileText className="h-5 w-5" />
                  ) : (
                    <FileSpreadsheet className="h-5 w-5" />
                  )}
                </div>
                <div className="min-w-0">
                  <p className="text-xs font-extrabold text-dark truncate">
                    {item.fileName}
                  </p>
                  <p className="text-[11px] font-medium text-slate-400 mt-0.5">
                    {item.generatedBy} • {item.dateTime}
                  </p>
                  <span
                    className={`mt-1.5 inline-flex items-center rounded-md px-2 py-0.5 text-[9px] font-extrabold uppercase ${
                      isPdf
                        ? "bg-rose-50 text-primary"
                        : "bg-emerald-50 text-emerald-700"
                    }`}
                  >
                    {item.format}
                  </span>
                </div>
              </div>

              <button
                type="button"
                onClick={() => onDownload(item)}
                aria-label={`Download ${item.fileName}`}
                className="flex h-9 w-9 flex-shrink-0 items-center justify-center rounded-xl bg-primary/10 text-primary hover:bg-primary hover:text-white transition-colors"
              >
                <Download className="h-4 w-4" />
              </button>
            </div>
          );
        })}
      </div>
    </div>
  );
}
